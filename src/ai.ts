function evaluateBoard(chess: Chess): number {
  let score = 0;
  const board = chess.board();
  for (let r = 0; r < 8; r++) {
    for (let c = 0; c < 8; c++) {
      const piece = board[r][c];
      if (!piece) continue;
      const value = PIECE_VALUES[piece.type];
      const pst = PST[piece.type];
      const idx = piece.color === 'w' ? (7 - r) * 8 + c : r * 8 + c;
      const posValue = pst ? pst[idx] : 0;
      const total = value + posValue;
      score += piece.color === 'w' ? total : -total;
    }
  }
  return score;
}

function minimax(
  chess: Chess,
  depth: number,
  alpha: number,
  beta: number,
  maximizing: boolean
): number {
  if (depth === 0 || chess.isGameOver()) {
    return evaluateBoard(chess);
  }

  const moves = chess.moves({ verbose: true });
  // Sort moves: captures first for better alpha-beta pruning
  moves.sort((a, b) => {
    const av = a.captured ? PIECE_VALUES[a.captured] : 0;
    const bv = b.captured ? PIECE_VALUES[b.captured] : 0;
    return bv - av;
  });

  if (maximizing) {
    let maxEval = -Infinity;
    for (const move of moves) {
      chess.move(move);
      const evalScore = minimax(chess, depth - 1, alpha, beta, false);
      chess.undo();
      maxEval = Math.max(maxEval, evalScore);
      alpha = Math.max(alpha, evalScore);
      if (beta <= alpha) break;
    }
    return maxEval;
  } else {
    let minEval = Infinity;
    for (const move of moves) {
      chess.move(move);
      const evalScore = minimax(chess, depth - 1, alpha, beta, true);
      chess.undo();
      minEval = Math.min(minEval, evalScore);
      beta = Math.min(beta, evalScore);
      if (beta <= alpha) break;
    }
    return minEval;
  }
}

function getDepth(difficulty: Difficulty): number {
  switch (difficulty) {
    case 'easy': return 2;
    case 'medium': return 3;
    case 'hard': return 4;
  }
}

export function findBestMove(fen: string, difficulty: Difficulty): { from: Square; to: Square; promotion?: string } | null {
  const chess = new Chess(fen);
  const moves = chess.moves({ verbose: true }) as Move[];
  if (moves.length === 0) return null;

  const depth = getDepth(difficulty);
  let bestMove: Move | null = null;
  let bestValue = -Infinity;

  // Sort moves for better pruning
  moves.sort((a, b) => {
    const av = a.captured ? PIECE_VALUES[a.captured] : 0;
    const bv = b.captured ? PIECE_VALUES[b.captured] : 0;
    return bv - av;
  });

  for (const move of moves) {
    chess.move(move);
    const value = minimax(chess, depth - 1, -Infinity, Infinity, false);
    chess.undo();
    if (value > bestValue) {
      bestValue = value;
      bestMove = move;
    }
  }

  if (!bestMove) return null;
  return {
    from: bestMove.from,
    to: bestMove.to,
    promotion: bestMove.promotion,
  };
}
